/** Live staged demo: wallet sign-in -> R2 upload -> paid verification -> USDC sale -> Worker ranges. */
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { Connection, Keypair, PublicKey } from '@solana/web3.js';
import { EdgeBountyClient } from '@edgebounty/blockchain-client';
import bs58 from 'bs58';
import nacl from 'tweetnacl';
const API = process.env.INTEGRATION_API ?? 'https://api.preview.13-61-207-211.sslip.io';
if (!API.includes('api.preview.13-61-207-211.sslip.io')) throw new Error('Only the isolated mock-USDC preview is supported');
const body = Buffer.from('category,value\nalpha,1\nbeta,2\n');
const digest = createHash('sha256').update(body).digest('hex');
const level = process.env.INTEGRATION_LEVEL === 'L3' ? 'L3' : 'L2';
const hex = (s: string) => Uint8Array.from(Buffer.from(s, 'hex'));
const request = async (method: string, path: string, token?: string, payload?: unknown) => {
  const r = await fetch(API + path, { method, headers: { ...(token ? { authorization: `Bearer ${token}` } : {}), ...(payload === undefined ? {} : { 'content-type': 'application/json' }) }, ...(payload === undefined ? {} : { body: JSON.stringify(payload) }), signal: AbortSignal.timeout(60_000) });
  const text = await r.text();
  if (!r.ok) throw new Error(`${method} ${path.split('/download/')[0]} failed (${r.status}): ${text.slice(0, 300)}`);
  return JSON.parse(text);
};
const cfg = await request('GET', '/config');
assert.equal(cfg.currency, 'USDC'); assert.equal(cfg.feeBps, 600); assert.equal(cfg.paymentReady, true);
const client = new EdgeBountyClient(new Connection('https://rpc.preview.13-61-207-211.sslip.io', 'confirmed'), new PublicKey(cfg.programId));
const actor = async () => {
  const kp = Keypair.generate(), wallet = kp.publicKey.toBase58();
  const ch = await request('POST', '/auth/challenge', undefined, { wallet });
  const signature = bs58.encode(nacl.sign.detached(new TextEncoder().encode(ch.message), kp.secretKey));
  const auth = await request('POST', '/auth/verify', undefined, { wallet, nonce: ch.nonce, signature });
  const funds = await request('POST', '/dev/faucet', auth.token, { wallet });
  assert.equal(funds.mockUsdc, 1000);
  return { kp, token: auth.token };
};
const seller = await actor(), buyer = await actor();
const pay = async (who: typeof seller, invoice: any) => {
  await client.send(await client.payService(who.kp.publicKey, hex(invoice.reference), invoice.serviceKind, BigInt(invoice.amountMicro)), [who.kp]);
  await request('POST', `/invoices/${invoice.id}/confirm`, who.token, {});
};
const { version } = await request('POST', '/assets', seller.token, { kind: 'dataset', name: 'Integration fixture CSV', purpose: 'listing', category: 'tabular' });
const up = await request('POST', `/versions/${version.id}/uploads`, seller.token, { path: 'fixture.csv', size: body.length, sha256: digest, mediaType: 'text/csv' });
assert.equal(up.directParts, true);
const md5 = createHash('md5').update(body).digest('base64');
const signed = await request('POST', `/uploads/${up.uploadId}/parts/1/url`, seller.token, { md5 });
assert.equal((await fetch(signed.url, { method: 'PUT', headers: signed.headers, body })).status, 200);
await request('POST', `/uploads/${up.uploadId}/complete`, seller.token, {});
await request('POST', `/versions/${version.id}/finalize`, seller.token, {});
console.log('Direct private R2 upload and finalization passed');
const check = await request('POST', '/verification/jobs', seller.token, { assetVersionId: version.id, level });
if (check.invoice) await pay(seller, check.invoice);
const deadline = Date.now() + 180_000;
for (;;) {
  const job = await request('GET', `/verification/jobs/${check.job.id}`, seller.token);
  if (job.status === 'completed') { assert.equal(job.result.report.passed, true, JSON.stringify(job.result.report)); break; }
  if (job.status === 'failed' || Date.now() > deadline) throw new Error(`Verification did not complete: ${job.status} ${job.error ?? ''}`);
  await new Promise((resolve) => setTimeout(resolve, 2000));
}
const reused = await request('POST', '/verification/jobs', seller.token, { assetVersionId: version.id, level });
assert.equal(reused.job.id, check.job.id);
assert.equal(reused.invoice, null);
assert.equal(reused.reused, true);
console.log(`Paid ${level} verification and no-charge result reuse passed`);
const listing = await request('POST', '/listings', seller.token, { assetVersionId: version.id, title: 'Integration fixture CSV', description: 'Disposable integration fixture for the isolated mock-USDC preview.', category: 'tabular', formats: ['csv'], licenseId: 'cc-by-4.0', priceMicro: '100000000' });
const l = listing.onchain;
await client.send((await client.createListing(seller.kp.publicKey, BigInt(l.listingId), 'dataset', { assetCommitment: hex(l.assetCommitment), termsHash: hex(l.termsHash), licenseHash: hex(l.licenseHash), price: BigInt(l.price) })).ixs, [seller.kp]);
await request('POST', `/listings/${listing.listing.id}/confirm`, seller.token, {});
const purchase = await request('POST', `/listings/${listing.listing.id}/purchase`, buyer.token, { accessMonths: 1 });
if (purchase.checkout.invoice) await pay(buyer, purchase.checkout.invoice);
const p = purchase.onchain;
const order = new PublicKey(p.address);
const treasury = new PublicKey(cfg.treasury), mint = new PublicKey(cfg.paymentMint);
const sellerBefore = await client.tokenBalance(client.ata(seller.kp.publicKey, mint)), treasuryBefore = await client.tokenBalance(treasury);
await client.send((await client.createOrder(buyer.kp.publicKey, new PublicKey(p.listing), BigInt(p.orderId), { expectedPrice: BigInt(p.expectedPrice), expectedVersion: p.expectedVersion })).ixs, [buyer.kp]);
await request('POST', `/orders/${purchase.order.id}/confirm`, buyer.token, {});
assert.equal((await fetch(`${API}/orders/${purchase.order.id}/delivery`, { headers: { authorization: `Bearer ${buyer.token}` } })).status, 409);
await client.send(await client.acceptDeliverable(buyer.kp.publicKey, order), [buyer.kp]);
await client.send(await client.settleOrder(seller.kp.publicKey, order), [seller.kp]);
await request('POST', `/orders/${purchase.order.id}/sync`, buyer.token, {});
assert.equal(await client.tokenBalance(client.ata(seller.kp.publicKey, mint)) - sellerBefore, 94_000_000n);
assert.equal(await client.tokenBalance(treasury) - treasuryBefore, 6_000_000n);
const delivery = await request('GET', `/orders/${purchase.order.id}/delivery`, buyer.token);
const downloadUrl = API + delivery.files[0].url;
const first = await fetch(downloadUrl, { headers: { range: 'bytes=0-4' } });
assert.equal(first.status, 206); assert.match(first.url, /workers\.dev/);
assert.equal(first.headers.get('x-download-accounting'), 'authorized-bytes');
const rest = await fetch(downloadUrl, { headers: { range: 'bytes=5-' } });
assert.equal(rest.status, 206);
assert.deepEqual(Buffer.concat([Buffer.from(await first.arrayBuffer()), Buffer.from(await rest.arrayBuffer())]), body);
const exhausted = await fetch(downloadUrl, { headers: { range: 'bytes=0-0' } });
assert.equal(exhausted.status, 402);
await client.send(await client.setListingActive(seller.kp.publicKey, new PublicKey(l.address), false), [seller.kp]);
await request('POST', `/listings/${listing.listing.id}/confirm`, seller.token, {});
console.log(JSON.stringify({ passed: true, directR2: true, paidVerification: true, currency: 'mock USDC', sellerNet: '94', commission: '6', unauthorizedBeforeSettlement: 'denied', workerRangeDownload: true, quotaExhaustion: 'denied', fixtureListingDelisted: true, order: order.toBase58() }));
