/** On-chain mock USDC acceptance test: 100 USDC bounty -> 94 seller, 6 treasury, exactly once. */
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import assert from 'node:assert/strict';
import { Connection, Keypair } from '@solana/web3.js';
import { EdgeBountyClient, fundTestUsdc } from '@edgebounty/blockchain-client';
import { fundSol } from './sol-platform.js';
process.loadEnvFile(join(import.meta.dirname, '../apps/api/.env'));
assert.equal(process.env.PAYMENT_CURRENCY, 'USDC');
assert.match(process.env.SOLANA_RPC_URL!, /^http:\/\/(127\.0\.0\.1|localhost):\d+\/?$/);
const connection = new Connection(process.env.SOLANA_RPC_URL!, 'confirmed');
const client = new EdgeBountyClient(connection);
const cfg = (await client.config())!;
assert.equal(cfg.feeBps, 600);
const admin = Keypair.fromSecretKey(Uint8Array.from(JSON.parse(readFileSync(join(import.meta.dirname, '../keys/localnet-authority.json'), 'utf8'))));
const verifier = Keypair.fromSecretKey(Uint8Array.from(JSON.parse(process.env.PLATFORM_VERIFIER_KEY!)));
const buyer = Keypair.generate(), seller = Keypair.generate();
for (const user of [buyer, seller]) await fundSol(connection, admin, user.publicKey, 2);
await fundTestUsdc(connection, admin, cfg.paymentMint, buyer.publicKey, 200_000_000n);
await fundTestUsdc(connection, admin, cfg.paymentMint, seller.publicKey, 0n);
const { order, ixs } = await client.createAndFundBounty(buyer.publicKey, BigInt(Date.now()), { amount: 100_000_000n, verifier: verifier.publicKey, verifierFee: 0n, verifierCapability: 1, termsHash: new Uint8Array(32).fill(1), criteriaHash: new Uint8Array(32).fill(2), licenseHash: new Uint8Array(32).fill(3), deadline: Math.floor(Date.now()/1000) + 3600, maxCorrections: 1 });
await client.send(ixs, [buyer]);
await client.send(await client.acceptBounty(seller.publicKey, order), [seller]);
await client.send(await client.submitDeliverable(seller.publicKey, order, new Uint8Array(32).fill(7), 1), [seller]);
const review = await client.submitOrderVerification(verifier.publicKey, order, { resultHash: new Uint8Array(32).fill(8), specHash: new Uint8Array(32).fill(9), benchmarkVersion: 1, passed: true });
await client.send(review.ixs, [verifier]);
await client.send(await client.acceptDeliverable(buyer.publicKey, order), [buyer]);
const before = await client.tokenBalance(cfg.treasury);
const signature = await client.send(await client.settleOrder(seller.publicKey, order), [seller]);
assert.equal((await client.order(order))?.state, 'settled');
assert.equal(await client.tokenBalance(client.ata(seller.publicKey, cfg.paymentMint)), 94_000_000n);
assert.equal(await client.tokenBalance(cfg.treasury) - before, 6_000_000n);
assert.equal((await client.licenseReceipt(order))?.granted, true);
await assert.rejects(async () => client.send(await client.settleOrder(seller.publicKey, order), [seller]));
console.log(JSON.stringify({ passed: true, currency: 'mock USDC', seller: '94', commission: '6', doubleSettlementRejected: true, order: order.toBase58(), signature }));
